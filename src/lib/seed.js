import { addDays, toISO, today } from './date'
import { DEFAULT_SETTINGS, FIELD_LABELS, PRIORITY_MAP, STATUS_MAP } from './constants'

const uid = (p) => `${p}_${Math.random().toString(36).slice(2, 9)}`

function d(offset) {
  return toISO(addDays(today(), offset))
}

/** 示例数据的历史要和真实写入保持同一种格式（存可读文案，不存 id） */
function history(entries) {
  return entries.map(([field, from, to, daysAgo]) => {
    const label = (v) => {
      if (field === 'status') return STATUS_MAP[v]?.name || v
      if (field === 'priority') return PRIORITY_MAP[v]?.name || v
      if (field === 'estimateHours') return `${v}h`
      return String(v)
    }
    return {
      id: uid('h'),
      at: Date.now() - daysAgo * 86400000,
      changes: [{ field, label: FIELD_LABELS[field] || field, from: label(from), to: label(to) }],
      note: '',
    }
  })
}

function comments(entries) {
  return entries.map(([author, text, daysAgo]) => ({
    id: uid('c'),
    at: Date.now() - daysAgo * 86400000,
    author,
    text,
  }))
}

